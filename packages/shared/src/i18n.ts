/**
 * `getLocaleFromNavigator()` usually returns region variants such as `ru-RU`,
 * but this project only ships base `en` and `ru` dictionaries.
 */
function getInitialLocale(): string {
  const locale = getLocaleFromNavigator();

  if (!locale) {
    return 'en';
  }

  return locale.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

